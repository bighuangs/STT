from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

from scripts.generate_openapi_typescript import generate


ROOT = Path(__file__).resolve().parents[2]
FRONTEND = ROOT / "frontend"
RUNTIME = FRONTEND / "src" / "runtime"
SNAPSHOTS = tuple(
    FRONTEND / "openapi" / f"{name}.json"
    for name in ("import-api", "query-api")
)


def test_openapi_typescript_clients_are_generated_and_current() -> None:
    missing = [path for path in SNAPSHOTS if not path.exists()]
    assert not missing, (
        "OpenAPI snapshots are required for the fast drift check. Run "
        "scripts/generate_openapi_typescript.py after both APIs are stable: "
        + ", ".join(str(path.relative_to(ROOT)) for path in missing)
    )
    result = subprocess.run(
        [sys.executable, "scripts/generate_openapi_typescript.py", "--check"],
        cwd=ROOT,
        check=False,
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    for name in ("import-api.ts", "query-api.ts"):
        source = (FRONTEND / "src" / "generated" / name).read_text(
            encoding="utf-8"
        )
        assert "Generated by scripts/generate_openapi_typescript.py" in source
        assert "export interface Operations" in source
        assert "export const operationDescriptors" in source
        assert "export const createClient" in source
        assert "headerParams:" in source
        assert "bodyRequired:" in source
        assert "ifMatchRequired:" in source
        if name == "import-api.ts":
            assert "/api/v1/workbench/knowledge-bases" in source
            assert "/api/v1/workbench/document-versions/{version_id}/chunks" in source
            assert "ifMatchRequired: true" in source
            assert '"file": File' in source


def test_generator_preserves_required_and_transport_contracts() -> None:
    document = {
        "components": {
            "parameters": {
                "DocumentId": {
                    "name": "document_id",
                    "in": "path",
                    "required": True,
                    "schema": {"type": "string"},
                },
                "IfMatch": {
                    "name": "If-Match",
                    "in": "header",
                    "schema": {"type": "string"},
                },
            },
            "schemas": {
                "MixedEnum": {"enum": [1, True, "manual"]},
                "JsonValue-Output": {
                    "anyOf": [
                        {"type": "string"},
                        {
                            "type": "array",
                            "items": {
                                "$ref": "#/components/schemas/JsonValue-Output"
                            },
                        },
                        {
                            "type": "object",
                            "additionalProperties": {
                                "$ref": "#/components/schemas/JsonValue-Output"
                            },
                        },
                        {"type": "null"},
                    ]
                },
                "Upload": {
                    "type": "object",
                    "required": ["file"],
                    "properties": {
                        "file": {"type": "string", "format": "binary"},
                        "parser_config": {"type": "string"},
                    },
                },
            },
        },
        "paths": {
            "/documents/{document_id}/versions": {
                "parameters": [
                    {"$ref": "#/components/parameters/DocumentId"},
                    {
                        "name": "revision",
                        "in": "query",
                        "schema": {"type": "integer"},
                    },
                ],
                "post": {
                    "operationId": "uploadVersion",
                    "x-stt-required-headers": ["If-Match"],
                    "parameters": [
                        {"$ref": "#/components/parameters/IfMatch"},
                        {
                            "name": "revision",
                            "in": "query",
                            "required": True,
                            "schema": {"type": "integer"},
                        },
                        {
                            "name": "Idempotency-Key",
                            "in": "header",
                            "required": True,
                            "schema": {"type": "string"},
                        },
                    ],
                    "requestBody": {
                        "required": True,
                        "content": {
                            "multipart/form-data": {
                                "schema": {"$ref": "#/components/schemas/Upload"}
                            }
                        },
                    },
                    "responses": {"204": {"description": "accepted"}},
                },
            },
            "/empty": {
                "get": {
                    "operationId": "empty",
                    "responses": {"200": {"description": "empty"}},
                }
            },
            "/source": {
                "get": {
                    "operationId": "source",
                    "responses": {
                        "200": {
                            "description": "binary source",
                            "content": {"application/pdf": {}},
                        }
                    },
                }
            },
        },
    }

    source = generate(document, "fixture")

    assert 'export type MixedEnum = 1 | true | "manual";' in source
    assert "export type JsonValue_Output = string" in source
    assert "Array<JsonValue_Output>" in source
    assert "{[key: string]: JsonValue_Output}" in source
    assert '"file": File' in source
    assert 'pathParams: { "document_id": string }' in source
    assert 'query: { "revision": number }' in source
    assert 'headerParams: { "Idempotency-Key": string }' in source
    assert "bodyRequired: true" in source
    assert "ifMatchRequired: true" in source
    assert 'contentType: "multipart/form-data"' in source
    assert "response: undefined" in source
    assert "response: Blob" in source

    without_extension = json.loads(json.dumps(document))
    del without_extension["paths"]["/documents/{document_id}/versions"]["post"][
        "x-stt-required-headers"
    ]
    optional_source = generate(without_extension, "fixture")
    assert "ifMatchRequired: false" in optional_source


def test_generator_rejects_required_header_extension_without_parameter() -> None:
    document = {
        "paths": {
            "/documents/{document_id}": {
                "patch": {
                    "operationId": "patchDocument",
                    "x-stt-required-headers": ["If-Match"],
                    "responses": {"204": {"description": "updated"}},
                }
            }
        }
    }

    try:
        generate(document, "invalid")
    except ValueError as error:
        assert "required OpenAPI header parameters are undeclared: if-match" in str(
            error
        )
    else:
        raise AssertionError("undeclared required header extension must fail generation")


