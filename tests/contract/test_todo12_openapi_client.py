def test_typescript_project_is_strict_and_dependency_free() -> None:
    package = json.loads((FRONTEND / "package.json").read_text(encoding="utf-8"))
    lock = json.loads((FRONTEND / "package-lock.json").read_text(encoding="utf-8"))
    tsconfig = json.loads((FRONTEND / "tsconfig.json").read_text(encoding="utf-8"))

    assert package.get("dependencies", {}) == {}
    assert package["devDependencies"] == {"typescript": "5.9.3"}
    assert lock["packages"][""].get("dependencies", {}) == {}
    assert tsconfig["compilerOptions"]["strict"] is True
    assert tsconfig["compilerOptions"]["noUncheckedIndexedAccess"] is True
    assert tsconfig["compilerOptions"]["exactOptionalPropertyTypes"] is True
    assert "type-tests/**/*.ts" in tsconfig["include"]
    assert package["scripts"]["typecheck"] == "tsc --noEmit"
